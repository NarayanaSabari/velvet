import { test, expect, resetWorkspaceData } from './fixtures'

test.describe.configure({ mode: 'serial' })
test.beforeAll(() => resetWorkspaceData())

for (const width of [1280, 390]) {
  test(`Mermaid comment workflow at ${width}px`, async ({ signedIn: page, request }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const response = await request.post('/api/v1/w/lab/issues', { data: { title: `Diagram review ${width}` } })
    expect(response.status()).toBe(201)
    const issue = await response.json()
    await page.goto(`/w/lab/issues/${issue.key}`)
    const draft = page.getByRole('textbox', { name: 'Comment', exact: true })
    await draft.fill('Proposed flow:\n\n')
    await draft.focus()
    await draft.press('ControlOrMeta+End')
    await page.getByRole('button', { name: '+ Diagram', exact: true }).click()
    await expect(draft).toHaveValue(/```mermaid/)
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    const preview = page.getByRole('region', { name: 'Comment preview' })
    const diagram = preview.getByRole('region', { name: 'Mermaid diagram', exact: true })
    await expect(diagram.locator('iframe[title="Rendered Mermaid diagram"]')).toBeVisible()
    await expect(preview.frameLocator('iframe[title="Rendered Mermaid diagram"]').locator('svg')).toBeVisible()
    await expect(preview.frameLocator('iframe[title="Rendered Mermaid diagram"]').locator('svg')).toContainText('Start')
    await diagram.getByRole('button', { name: 'Source', exact: true }).click()
    await expect(diagram.locator('pre')).toContainText('flowchart TD')
    await diagram.getByRole('button', { name: 'Diagram', exact: true }).click()
    const expand = diagram.getByRole('button', { name: 'Expand', exact: true })
    await expand.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.frameLocator('dialog iframe').locator('svg')).toBeVisible()
    const bounds = await page.getByRole('dialog').boundingBox()
    expect(bounds).not.toBeNull()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(expand).toBeFocused()
    await page.getByRole('button', { name: 'Write', exact: true }).click()
    const saved = await draft.inputValue()
    await page.getByRole('button', { name: 'Comment', exact: true }).click()
    await expect(draft).toHaveValue('')
    await page.reload()
    await expect(page.locator('iframe[title="Rendered Mermaid diagram"]')).toHaveCount(1)
    await expect(page.frameLocator('iframe[title="Rendered Mermaid diagram"]').locator('svg')).toContainText('Next step')
    // The public API stores the original Markdown, not a browser-generated SVG.
    const comments = await request.get(`/api/v1/w/lab/issues/${issue.key}/comments`).then(r => r.json())
    expect(JSON.stringify(comments)).toContain(JSON.stringify(saved).slice(1, -1))
    for (const colorScheme of ['light', 'dark'] as const) {
      await page.emulateMedia({ colorScheme })
      await expect(page.frameLocator('iframe[title="Rendered Mermaid diagram"]').locator('svg')).toBeVisible()
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `test-results/mermaid-${width}-${colorScheme}.png`, fullPage: true })
    }
    await draft.fill('```mermaid\nnot a diagram\n```')
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(preview.getByRole('alert')).toContainText('Could not render')
    await preview.getByRole('button', { name: 'View source', exact: true }).click()
    await expect(preview.locator('pre')).toContainText('not a diagram')
    await page.getByRole('button', { name: 'Write', exact: true }).click()
    await expect(draft).toHaveValue('```mermaid\nnot a diagram\n```')
  })
}

test('mixed Markdown renders multiple diagrams without executing diagram links', async ({ signedIn: page, request }) => {
  const created = await request.post('/api/v1/w/lab/issues', { data: { title: 'Mixed diagram formats' } })
  const issue = await created.json()
  const body = [
    '**Architecture review**',
    '```mermaid\nsequenceDiagram\n  participant CLI\n  participant API\n  CLI->>API: Resolve workspace\n  API-->>CLI: Workspace\n```',
    '```js\nconst ordinaryCode = true\n```',
    '```mermaid\nflowchart LR\n  A[Request] --> B[Response]\n  click A "javascript:alert(1)"\n```',
  ].join('\n\n')
  const posted = await request.post(`/api/v1/w/lab/issues/${issue.key}/comments`, { data: { body } })
  expect(posted.status()).toBe(201)
  await page.goto(`/w/lab/issues/${issue.key}`)
  await expect(page.locator('iframe[title="Rendered Mermaid diagram"]')).toHaveCount(2)
  const frames = page.locator('iframe[title="Rendered Mermaid diagram"]')
  await expect(frames.nth(0).contentFrame().locator('svg')).toContainText('Resolve workspace')
  await expect(frames.nth(1).contentFrame().locator('svg')).toContainText('Response')
  await expect(frames.nth(1).contentFrame().locator('a, script, foreignObject')).toHaveCount(0)
  await expect(page.getByText('const ordinaryCode = true')).toBeVisible()
  await expect(page.getByText('Architecture review', { exact: true })).toBeVisible()
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  const diagram = page.getByRole('region', { name: 'Mermaid diagram', exact: true }).first()
  await diagram.getByRole('button', { name: 'Copy source' }).click()
  await expect(diagram.getByRole('status')).toHaveText('Source copied')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('sequenceDiagram')
})

test('diagram configuration and external images cannot run from a comment', async ({ signedIn: page, request }) => {
  const response = await request.post('/api/v1/w/lab/issues', { data: { title: 'Diagram security' } })
  const issue = await response.json()
  await page.goto(`/w/lab/issues/${issue.key}`)
  const draft = page.getByRole('textbox', { name: 'Comment', exact: true })
  await draft.fill('```mermaid\n%%{init: {"securityLevel":"loose"}}%%\nflowchart LR\nA-->B\n```')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('configuration is not supported')
  await page.getByRole('button', { name: 'Write', exact: true }).click()
  await draft.fill('```mermaid\nflowchart LR\nA@{ img: "https://example.com/tracker.png" }\n```')
  const external: string[] = []
  page.on('request', r => { if (r.url().includes('example.com')) external.push(r.url()) })
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('External images are not supported')
  expect(external).toEqual([])
})
